import { Calendar, Clock, Bell, AlertCircle, CheckCircle2, Plus, Zap, X } from 'lucide-react';
import { useMemo, useState } from 'react';
import { RegisterOvulationModal, OvulationData } from './RegisterOvulationModal';
import { RegisterInseminationModal, InseminationData } from './RegisterInseminationModal';
import { ConfirmPregnancyModal, PregnancyData } from './ConfirmPregnancyModal';
import { NativeSelect } from '../ui/native-select';
import type { Animal, CreateReproductiveEventInput, ReproductiveEvent } from '@/types';
import { toast } from 'sonner';

interface ReproductionAutomationTabProps {
  onNavigateToAgenda?: () => void;
  events?: ReproductiveEvent[];
  harasId?: string;
  mares?: Animal[];
  onCreateEvent?: (input: CreateReproductiveEventInput) => Promise<ReproductiveEvent>;
  onConfirmGestation?: (input: {
    mareId: string;
    stallionId?: string;
    confirmationDate: string;
    method: string;
    observations?: string;
  }) => Promise<void> | void;
}

interface AutoEvent {
  id: string;
  type: string;
  animal: string;
  scheduledDate: string;
  scheduledTime: string;
  daysUntil: number;
  priority: string;
  autoGenerated: boolean;
  originEvent?: string;
  notes?: string;
}

const mapEventTypeLabel = (eventType?: string | null) => {
  switch (eventType) {
    case 'ovulacao':
      return 'Ovulação';
    case 'inseminacao':
      return 'Inseminação';
    case 'coleta_ovulos':
      return 'Coleta de Embrião';
    case 'transferencia_embriao':
      return 'Transferência de Embrião';
    case 'diagnostico_gestacao':
      return 'Diagnóstico de Gestação';
    case 'aplicacao_p4':
      return 'Aplicação P4';
    case 'cobertura':
      return 'Cobertura';
    default:
      return 'Evento Reprodutivo';
  }
};

export function ReproductionAutomationTab({
  onNavigateToAgenda,
  events = [],
  harasId,
  mares = [],
  onCreateEvent,
  onConfirmGestation,
}: ReproductionAutomationTabProps = {}) {
  const [showOvulationModal, setShowOvulationModal] = useState(false);
  const [showInseminationModal, setShowInseminationModal] = useState(false);
  const [showPregnancyModal, setShowPregnancyModal] = useState(false);
  const [successMessage, setSuccessMessage] = useState<string | null>(null);
  const [newEventsCount, setNewEventsCount] = useState(0);
  const [selectedMareId, setSelectedMareId] = useState('');

  // Handler para ver eventos no calendário
  const handleViewCalendar = () => {
    // Navega para a aba Agenda
    if (onNavigateToAgenda) {
      onNavigateToAgenda();
    }
  };

  const autoEvents: AutoEvent[] = useMemo(() => {
    if (!events || events.length === 0) {
      return [];
    }

    return events.map((event) => {
      const date = event.event_date;
      const scheduledDate = date;
      const daysUntil = date
        ? Math.ceil((new Date(date).getTime() - Date.now()) / (1000 * 60 * 60 * 24))
        : 0;
      const details = event.details as Record<string, any> | null;
      const label = details?.label || mapEventTypeLabel(event.event_type);

      return {
        id: event.id,
        type: label,
        animal: event.mare?.name || event.animal?.name || event.stallion?.name || 'Animal',
        scheduledDate,
        scheduledTime: details?.time || '09:00',
        daysUntil,
        priority: event.priority || details?.priority || 'Média',
        autoGenerated: Boolean(event.auto_generated),
        originEvent: details?.originEvent || undefined,
        notes: event.observations || details?.notes || undefined,
      };
    });
  }, [events]);

  const selectedMare = useMemo(
    () => mares.find((mare) => mare.id === selectedMareId),
    [mares, selectedMareId]
  );

  const formatDateLabel = (value?: string | null) => {
    if (!value) return '';
    const [year, month, day] = value.split('T')[0].split('-');
    if (!year || !month || !day) return value;
    return `${day}/${month}/${year}`;
  };

  const ensureMareSelected = () => {
    if (!selectedMare) {
      toast.error('Selecione uma égua para registrar o evento.');
      return null;
    }
    if (!harasId) {
      toast.error('Haras não identificado.');
      return null;
    }
    if (!onCreateEvent) {
      toast.error('Integração com eventos indisponível.');
      return null;
    }
    return selectedMare;
  };

  const createEvent = async (input: CreateReproductiveEventInput) => {
    if (!onCreateEvent) return null;
    return await onCreateEvent(input);
  };

  // Estatísticas
  const stats = {
    totalAutomated: autoEvents.filter(e => e.autoGenerated).length,
    highPriority: autoEvents.filter(e => e.priority === 'Alta').length,
    nextWeek: autoEvents.filter(e => e.daysUntil <= 7).length,
  };

  const getEventIcon = (type: string) => {
    switch (type) {
      case 'Ovulação':
        return <Calendar className="w-5 h-5" />;
      case 'Coleta de Embrião':
        return <Bell className="w-5 h-5" />;
      case 'Aplicação P4':
        return <AlertCircle className="w-5 h-5" />;
      case 'Diagnóstico de Gestação':
        return <CheckCircle2 className="w-5 h-5" />;
      case 'Inseminação':
        return <Plus className="w-5 h-5" />;
      default:
        return <Calendar className="w-5 h-5" />;
    }
  };

  const getPriorityColor = (priority: string) => {
    switch (priority) {
      case 'Alta':
        return 'bg-red-100 dark:bg-red-900/20 text-red-700 dark:text-red-400 border-red-200 dark:border-red-800';
      case 'Média':
        return 'bg-yellow-100 dark:bg-yellow-900/20 text-yellow-700 dark:text-yellow-400 border-yellow-200 dark:border-yellow-800';
      case 'Baixa':
        return 'bg-green-100 dark:bg-green-900/20 text-green-700 dark:text-green-400 border-green-200 dark:border-green-800';
      default:
        return 'bg-gray-100 dark:bg-gray-900/20 text-gray-700 dark:text-gray-400 border-gray-200 dark:border-gray-800';
    }
  };

  const getDaysColor = (days: number) => {
    if (days <= 3) return 'text-red-600 dark:text-red-400 font-semibold';
    if (days <= 7) return 'text-orange-600 dark:text-orange-400 font-medium';
    return 'text-foreground dark:text-white';
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="bg-gray-50 dark:bg-[#1a1a1a] rounded-xl p-6 border-2 border-gray-200 dark:border-white/20">
        <div className="flex items-start justify-between mb-4">
          <div>
            <div className="flex items-center gap-2 mb-2">
              <Zap className="w-6 h-6 text-foreground dark:text-white" />
              <h2 className="text-2xl text-foreground dark:text-white">Sequência Automática</h2>
            </div>
            <p className="text-muted-foreground dark:text-white/70">
              Eventos de reprodução agendados automaticamente pelo sistema
            </p>
          </div>
        </div>

        {/* Estatísticas */}
        <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 mt-6">
          <div className="bg-white dark:bg-white/5 backdrop-blur rounded-lg p-4 border border-gray-200 dark:border-white/20">
            <div className="flex items-center gap-2 mb-1">
              <Zap className="w-5 h-5 text-foreground dark:text-white" />
              <p className="text-sm text-muted-foreground dark:text-white/70">Automáticos</p>
            </div>
            <p className="text-3xl font-semibold text-foreground dark:text-white">{stats.totalAutomated}</p>
          </div>
          <div className="bg-white dark:bg-white/5 backdrop-blur rounded-lg p-4 border border-gray-200 dark:border-white/20">
            <div className="flex items-center gap-2 mb-1">
              <AlertCircle className="w-5 h-5 text-foreground dark:text-white" />
              <p className="text-sm text-muted-foreground dark:text-white/70">Alta Prioridade</p>
            </div>
            <p className="text-3xl font-semibold text-foreground dark:text-white">{stats.highPriority}</p>
          </div>
          <div className="bg-white dark:bg-white/5 backdrop-blur rounded-lg p-4 border border-gray-200 dark:border-white/20">
            <div className="flex items-center gap-2 mb-1">
              <Clock className="w-5 h-5 text-foreground dark:text-white" />
              <p className="text-sm text-muted-foreground dark:text-white/70">Próximos 7 dias</p>
            </div>
            <p className="text-3xl font-semibold text-foreground dark:text-white">{stats.nextWeek}</p>
          </div>
        </div>

        {/* Ações rápidas */}
        <div className="mt-6 grid grid-cols-1 lg:grid-cols-[minmax(0,1fr)_auto_auto_auto] gap-3">
          <NativeSelect
            value={selectedMareId}
            onChange={(e) => setSelectedMareId(e.target.value)}
            className="w-full h-10 bg-white dark:bg-[#0d0d0d] border border-gray-200 dark:border-[rgba(255,255,255,0.1)] text-foreground dark:text-white rounded-lg"
          >
            <option value="">Selecione a égua</option>
            {mares.map((mare) => (
              <option key={mare.id} value={mare.id}>
                {mare.name}
              </option>
            ))}
          </NativeSelect>
          <button
            onClick={() => {
              if (!ensureMareSelected()) return;
              setShowOvulationModal(true);
            }}
            className="w-full lg:w-auto px-4 py-2 bg-primary dark:bg-white text-white dark:text-black rounded-lg hover:opacity-90 transition-opacity flex items-center justify-center gap-2"
          >
            Registrar Ovulação
          </button>
          <button
            onClick={() => {
              if (!ensureMareSelected()) return;
              setShowInseminationModal(true);
            }}
            className="w-full lg:w-auto px-4 py-2 bg-primary/10 dark:bg-white/10 text-foreground dark:text-white rounded-lg hover:opacity-90 transition-opacity flex items-center justify-center gap-2 border border-primary/20 dark:border-white/20"
          >
            Registrar Inseminação
          </button>
          <button
            onClick={() => {
              if (!ensureMareSelected()) return;
              setShowPregnancyModal(true);
            }}
            className="w-full lg:w-auto px-4 py-2 bg-transparent text-foreground dark:text-white rounded-lg hover:bg-white/60 dark:hover:bg-white/10 transition-colors border border-gray-200 dark:border-white/20"
          >
            Confirmar Gestação
          </button>
        </div>
      </div>

      {/* Timeline */}
      <div className="bg-white dark:bg-[#1a1a1a] rounded-xl border border-gray-200 dark:border-[rgba(255,255,255,0.1)] p-6">
        <div className="flex flex-col gap-4 mb-6">
          <div>
            <h3 className="text-lg text-foreground dark:text-white mb-1">Próximos Eventos Automáticos</h3>
            <p className="text-sm text-muted-foreground dark:text-[#99a1af]">
              {autoEvents.length} eventos agendados nos próximos 30 dias
            </p>
          </div>
          <button className="w-full sm:w-auto px-4 py-2 bg-primary dark:bg-white text-white dark:text-black rounded-lg hover:opacity-90 transition-opacity flex items-center justify-center gap-2" onClick={handleViewCalendar}>
            <Calendar className="w-4 h-4" />
            Ver no Calendário
          </button>
        </div>

        <div className="space-y-3">
          {autoEvents.map(event => {
            const [year, month, day] = event.scheduledDate ? event.scheduledDate.split('-') : [];
            const formattedDate = year && month && day ? `${day}/${month}/${year}` : '-';

            return (
              <div
                key={event.id}
                className="border border-gray-200 dark:border-[rgba(255,255,255,0.1)] rounded-lg p-4 hover:border-primary dark:hover:border-white/40 transition-all group"
              >
                <div className="flex flex-col sm:flex-row items-start gap-4">
                  <div className="flex-1 w-full">
                    <div className="flex items-start gap-3 mb-3">
                      <div className="w-10 h-10 bg-gray-100 dark:bg-[#2a2a2a] rounded-full flex items-center justify-center flex-shrink-0 text-foreground dark:text-white">
                        {getEventIcon(event.type)}
                      </div>
                      <div className="flex-1 min-w-0">
                        <div className="flex items-center gap-2 flex-wrap mb-1">
                          <h4 className="text-foreground dark:text-white font-medium">
                            {event.type}
                          </h4>
                          {event.autoGenerated && (
                            <span className="inline-flex items-center gap-1 px-2 py-0.5 bg-gray-100 dark:bg-[#2a2a2a] text-foreground dark:text-white rounded text-xs border border-gray-300 dark:border-[rgba(255,255,255,0.1)]">
                              <Zap className="w-3 h-3" />
                              Automático
                            </span>
                          )}
                          <span className={`inline-flex items-center px-2 py-0.5 rounded text-xs border ${getPriorityColor(event.priority)}`}>
                            {event.priority}
                          </span>
                        </div>
                        <p className="text-sm text-foreground dark:text-white mb-1">
                          Animal: <span className="font-medium">{event.animal}</span>
                        </p>
                        {event.originEvent && (
                          <p className="text-xs text-muted-foreground dark:text-[#99a1af] mb-2">
                            ↳ {event.originEvent}
                          </p>
                        )}
                        {event.notes && (
                          <p className="text-xs text-muted-foreground dark:text-[#99a1af]">
                            {event.notes}
                          </p>
                        )}
                      </div>
                    </div>
                  </div>

                  <div className="w-full sm:w-auto sm:text-right flex sm:flex-col gap-2 sm:gap-0 flex-wrap sm:flex-nowrap sm:ml-4">
                    <div className="flex items-center gap-2 sm:mb-2">
                      <Calendar className="w-4 h-4 text-muted-foreground dark:text-[#99a1af]" />
                      <span className="text-sm text-foreground dark:text-white font-medium">
                        {formattedDate}
                      </span>
                    </div>
                    <div className="flex items-center gap-2 sm:mb-2">
                      <Clock className="w-4 h-4 text-muted-foreground dark:text-[#99a1af]" />
                      <span className="text-sm text-muted-foreground dark:text-[#99a1af]">
                        {event.scheduledTime}
                      </span>
                    </div>
                    <div className={`text-sm ${getDaysColor(event.daysUntil)}`}>
                      Em {event.daysUntil} {event.daysUntil === 1 ? 'dia' : 'dias'}
                    </div>
                  </div>
                </div>
              </div>
            );
          })}
        </div>

        {autoEvents.length === 0 && (
          <div className="text-center py-12">
            <CheckCircle2 className="w-12 h-12 text-muted-foreground dark:text-[#99a1af] mx-auto mb-4" />
            <p className="text-foreground dark:text-white mb-2">Nenhum evento automático agendado</p>
            <p className="text-sm text-muted-foreground dark:text-[#99a1af]">
              Use as ações rápidas acima para criar novos eventos
            </p>
          </div>
        )}
      </div>

      {/* Modais */}
      {showOvulationModal && (
        <RegisterOvulationModal
          animalName={selectedMare?.name || 'Égua'}
          onClose={() => setShowOvulationModal(false)}
          onRegister={async (data: OvulationData) => {
            const mare = ensureMareSelected();
            if (!mare || !harasId) return;
            try {
              await createEvent({
                haras_id: harasId,
                animal_id: mare.id,
                mare_id: mare.id,
                event_type: 'ovulacao',
                event_date: data.date,
                observations: data.observations || undefined,
                details: {
                  time: data.time,
                  label: 'Ovulação',
                },
                auto_generated: false,
                priority: 'Média',
              });

              let autoCount = 0;
              if (data.autoScheduleCollection && data.collectionDate) {
                await createEvent({
                  haras_id: harasId,
                  animal_id: mare.id,
                  mare_id: mare.id,
                  event_type: 'coleta_ovulos',
                  event_date: data.collectionDate,
                  details: {
                    time: data.collectionTime || data.time,
                    label: 'Coleta de Embrião',
                    originEvent: `Ovulação em ${formatDateLabel(data.date)}`,
                  },
                  auto_generated: true,
                  priority: 'Média',
                });
                autoCount = 1;
              }

              setSuccessMessage(
                autoCount > 0
                  ? `Ovulação registrada! Coleta automática agendada para ${formatDateLabel(data.collectionDate)}.`
                  : 'Ovulação registrada com sucesso!'
              );
              setNewEventsCount(autoCount);
              setShowOvulationModal(false);
              setTimeout(() => setSuccessMessage(null), 5000);
            } catch (error) {
              console.error('Erro ao registrar ovulação:', error);
              toast.error('Erro ao registrar ovulação. Tente novamente.');
            }
          }}
        />
      )}
      
      {showInseminationModal && (
        <RegisterInseminationModal
          animalName={selectedMare?.name || 'Égua'}
          onClose={() => setShowInseminationModal(false)}
          onRegister={async (data: InseminationData) => {
            const mare = ensureMareSelected();
            if (!mare || !harasId) return;
            try {
              await createEvent({
                haras_id: harasId,
                animal_id: mare.id,
                mare_id: mare.id,
                event_type: 'inseminacao',
                event_date: data.date,
                semen_type: data.semenType,
                observations: data.observations || undefined,
                details: {
                  time: data.time,
                  stallionName: data.stallionName || undefined,
                  semenType: data.semenType,
                },
                auto_generated: false,
                priority: 'Média',
              });

              let autoCount = 0;
              if (data.autoScheduleCollection && data.collectionDate) {
                await createEvent({
                  haras_id: harasId,
                  animal_id: mare.id,
                  mare_id: mare.id,
                  event_type: 'coleta_ovulos',
                  event_date: data.collectionDate,
                  details: {
                    time: data.collectionTime || data.time,
                    label: 'Coleta de Embrião',
                    originEvent: `Inseminação em ${formatDateLabel(data.date)}`,
                  },
                  auto_generated: true,
                  priority: 'Média',
                });
                autoCount = 1;
              }

              setSuccessMessage(
                autoCount > 0
                  ? `Inseminação registrada! Coleta automática agendada para ${formatDateLabel(data.collectionDate)}.`
                  : 'Inseminação registrada com sucesso!'
              );
              setNewEventsCount(autoCount);
              setShowInseminationModal(false);
              setTimeout(() => setSuccessMessage(null), 5000);
            } catch (error) {
              console.error('Erro ao registrar inseminação:', error);
              toast.error('Erro ao registrar inseminação. Tente novamente.');
            }
          }}
        />
      )}
      
      {showPregnancyModal && (
        <ConfirmPregnancyModal
          animalName={selectedMare?.name || 'Égua'}
          onClose={() => setShowPregnancyModal(false)}
          onConfirm={async (data: PregnancyData) => {
            const mare = ensureMareSelected();
            if (!mare || !harasId) return;
            try {
              await onConfirmGestation?.({
                mareId: mare.id,
                confirmationDate: data.confirmationDate,
                method: data.method,
                observations: data.observations,
              });

              await createEvent({
                haras_id: harasId,
                animal_id: mare.id,
                mare_id: mare.id,
                event_type: 'diagnostico_gestacao',
                event_date: data.confirmationDate,
                observations: data.observations || undefined,
                details: {
                  time: data.confirmationTime,
                  label: 'Diagnóstico de Gestação',
                },
                auto_generated: false,
                priority: 'Média',
              });

              let autoCount = 0;
              if (data.autoScheduleP4 && data.p4Schedule && data.p4Schedule.length > 0) {
                for (const app of data.p4Schedule) {
                  await createEvent({
                    haras_id: harasId,
                    animal_id: mare.id,
                    mare_id: mare.id,
                    event_type: 'aplicacao_p4',
                    event_date: app.date,
                    details: {
                      time: app.time,
                      label: 'Aplicação P4',
                      applicationNumber: app.applicationNumber,
                      gestationDay: app.gestationDay,
                      originEvent: `Diagnóstico em ${formatDateLabel(data.confirmationDate)}`,
                    },
                    auto_generated: true,
                    priority: 'Média',
                  });
                  autoCount += 1;
                }
              }

              setSuccessMessage(
                autoCount > 0
                  ? `Gestação confirmada! ${autoCount} aplicações P4 agendadas automaticamente.`
                  : 'Gestação confirmada com sucesso!'
              );
              setNewEventsCount(autoCount);
              setShowPregnancyModal(false);
              setTimeout(() => setSuccessMessage(null), 5000);
            } catch (error) {
              console.error('Erro ao confirmar gestação:', error);
              toast.error('Erro ao confirmar gestação. Tente novamente.');
            }
          }}
        />
      )}

      {/* Mensagem de Sucesso */}
      {successMessage && (
        <div className="fixed bottom-6 right-6 bg-green-100 dark:bg-green-900/30 border-2 border-green-500 dark:border-green-600 text-green-800 dark:text-green-300 rounded-xl p-4 shadow-2xl max-w-md z-50 animate-slide-up">
          <div className="flex items-start gap-3">
            <div className="w-8 h-8 bg-green-600 dark:bg-green-500 rounded-full flex items-center justify-center flex-shrink-0">
              <CheckCircle2 className="w-5 h-5 text-white" />
            </div>
            <div className="flex-1">
              <p className="font-medium mb-1">{successMessage}</p>
              {newEventsCount > 0 && (
                <p className="text-sm text-green-700 dark:text-green-400">
                  {newEventsCount} {newEventsCount === 1 ? 'novo evento agendado' : 'novos eventos agendados'}
                </p>
              )}
            </div>
            <button
              onClick={() => setSuccessMessage(null)}
              className="p-1 hover:bg-green-200 dark:hover:bg-green-800 rounded transition-colors"
            >
              <X className="w-4 h-4" />
            </button>
          </div>
        </div>
      )}
    </div>
  );
}
